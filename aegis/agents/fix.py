"""Fix agent: prepares a minimal patch (or an ops action) in a sandbox, never in production.

    verified RCA -> sandbox -> patch -> reproduction test -> test suite -> static checks
                 -> secret scan -> PR draft -> [human approval] -> branch / control-plane action
"""
from __future__ import annotations

import asyncio
import json
import re
from pathlib import Path

from pydantic import BaseModel, Field

from aegis.agents.base import Agent
from aegis.agents.models import AgentResult, AgentTask
from aegis.agents.verification import (incident_traffic, replay_verdict, runtime_for, signature_rate, signatures,
                                       tolerance)
from aegis.config import get_settings
from aegis.llm.router import get_llm
from aegis.sandbox.executor import Sandbox, SandboxError
from aegis.security.pii import scan_secrets
from aegis.tools.gateway import ToolGateway


class PatchDraft(BaseModel):
    patch: str = Field(description="unified diff against HEAD")
    rationale: str


class PRText(BaseModel):
    title: str
    body: str


def yaml_literal(v) -> str:
    return "null" if v is None else str(v)


def set_yaml_leaf(text: str, dotted: str, value) -> str:
    section, leaf = dotted.split(".", 1)
    lines = text.splitlines(keepends=True)
    in_section = False
    for i, line in enumerate(lines):
        if re.match(rf"^{re.escape(section)}:\s*$", line):
            in_section = True
            continue
        if in_section and re.match(r"^\S", line):
            in_section = False
        if in_section and re.match(rf"^\s+{re.escape(leaf)}:", line):
            indent = re.match(r"^(\s+)", line).group(1)
            lines[i] = f"{indent}{leaf}: {yaml_literal(value)}\n"
            return "".join(lines)
    raise ValueError(f"{dotted} not found")


REPRO_TEST = '''"""Regression test generated by AegisAI for {incident_id}.

Root cause: {title}.
Replays {n} recorded production requests from the incident window through the
service and asserts the error rate stays at the pre-incident baseline.
"""
import json
from pathlib import Path

from platform_sim.replay import replay

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = Path(__file__).parent / "fixtures" / "{fixture}"


def test_{slug}_does_not_reproduce():
    data = json.loads(FIXTURE.read_text())
    report = replay(ROOT, data["service"], data["traffic"], data.get("runtime"))
    if data["signatures"]:
        failures = sum(report["errors_by_type"].get(s, 0) for s in data["signatures"])
    else:
        failures = report["failed"]
    assert failures / report["requests"] <= data["max_failure_rate"], report
'''


class FixAgent(Agent):
    name = "fix"
    title = "Fix Agent"
    description = "Generates and tests minimal remediations in a sandbox; applies them only with approval."
    skills = [
        {"id": "prepare-fix", "name": "Prepare fix",
         "description": "Config/code/migration patch plus a replay-based reproduction test, or an ops action plan.",
         "tags": ["remediation", "patch", "sandbox", "pull-request"]},
        {"id": "apply-fix", "name": "Apply approved fix",
         "description": "Creates the fix branch or runs the control-plane action with a human approval token.",
         "tags": ["remediation", "approval"]},
    ]

    async def execute(self, task: AgentTask, gw: ToolGateway) -> AgentResult:
        if task.params.get("action") == "apply":
            return await self.apply(task, gw)
        hyp = task.params["hypothesis"]
        kind = hyp["fix_kind"]
        if kind == "ops_action":
            fix = await self.ops_fix(task, gw, hyp)
        elif kind in ("config_revert", "code_revert", "migration"):
            fix = await self.patch_fix(task, gw, hyp)
        else:
            fix = {"kind": "manual", "summary": f"Roll back to the previous release ({hyp['culprit']}); "
                                                "no targeted fix pattern is known.", "actions": []}
        fix["pr"] = await self.pr_text(task, hyp, fix)
        return AgentResult(task_id=task.task_id, agent=self.name, summary=fix.get("summary", ""),
                           data={"fix": fix}, status="completed" if fix.get("ok", True) else "failed")

    # -- code / config / schema patches --------------------------------------------------
    async def patch_fix(self, task: AgentTask, gw: ToolGateway, hyp: dict) -> dict:
        service, onset = task.incident.service, task.params["onset"]
        pkg = service.replace("-", "_")
        culprit = hyp["culprit"]
        repo = Path(task.workspace) / "repo"
        traffic, pre = await incident_traffic(gw, service, onset)
        rt_incident, _ = runtime_for(hyp, task.params["evidence"], service)
        code_diff = None
        if hyp["fix_kind"] == "code_revert":
            code_diff = (await gw.call("git.git_diff", base=f"{culprit['commit']}^", head=culprit["commit"],
                                       path=culprit["file"]))["diff"]
        index_stmt = None
        if hyp["fix_kind"] == "migration":
            idx = next((i for i in culprit.get("indexes", []) if i.endswith("_customer_id")),
                       (culprit.get("indexes") or [None])[0])
            found = await gw.call("git.search_repository", pattern=rf"CREATE INDEX {idx}\b", path_glob="migrations/*")
            if found["matches"]:
                index_stmt = found["matches"][0]["text"].replace("CREATE INDEX", "CREATE INDEX IF NOT EXISTS")
        slug = re.sub(r"\W+", "_", task.incident.incident_id.lower())
        sigs = signatures(task.params["evidence"])
        fixture_name = f"{slug}_traffic.json"
        test_rel = f"tests/test_repro_{slug}.py"
        llm = get_llm()

        def work() -> dict:
            timeout = get_settings().sandbox_timeout_s
            with Sandbox(repo, "HEAD", timeout, agent=self.name) as sbx:
                changed: list[str] = []
                if hyp["fix_kind"] == "config_revert":
                    rel = f"services/{pkg}/config.yaml"
                    text = sbx.read(rel)
                    for ch in culprit.get("changes", []):
                        text = set_yaml_leaf(text, ch["key"], ch["old"])
                    sbx.write(rel, text)
                    changed.append(rel)
                    desc = ", ".join(f"{c['key']}: {yaml_literal(c['new'])} -> {yaml_literal(c['old'])}"
                                     for c in culprit.get("changes", []))
                elif hyp["fix_kind"] == "code_revert":
                    try:
                        sbx.apply_patch(code_diff, reverse=True)
                        desc = f"revert the {culprit['file']} hunk from {culprit['commit'][:8]}"
                    except SandboxError:
                        return {"ok": False, "error": "targeted revert does not apply cleanly on HEAD",
                                "needs_llm_patch": True}
                    changed.append(culprit["file"])
                else:
                    if not index_stmt:
                        return {"ok": False, "error": "original index definition not found"}
                    n = len([f for f in sbx.listdir("migrations") if f.endswith(".sql")]) + 1
                    idx_name = re.search(r"EXISTS (\w+)", index_stmt).group(1)
                    rel = f"migrations/{n:04d}_restore_{idx_name}.sql"
                    sbx.write(rel, f"-- Restore index dropped in {culprit['commit'][:8]} (incident "
                                   f"{task.incident.incident_id}); required by the customer history query.\n"
                                   f"{index_stmt}\n")
                    changed.append(rel)
                    desc = f"new migration recreating {idx_name}"
                fixed_patch = sbx.diff()
                r_pre = sbx.replay(service, pre, rt_incident)
                r_fixed = sbx.replay(service, traffic, rt_incident)
                rp = signature_rate(r_pre, sigs)
                threshold = round(rp + tolerance(rp, r_pre["requests"], sigs), 4)
                fixture = {"service": service, "incident": task.incident.incident_id, "runtime": rt_incident,
                           "signatures": sigs, "max_failure_rate": threshold, "traffic": traffic}
                test_files = {
                    f"tests/fixtures/{fixture_name}": json.dumps(fixture, separators=(",", ":")) + "\n",
                    test_rel: REPRO_TEST.format(incident_id=task.incident.incident_id, title=hyp["title"],
                                                n=len(traffic), fixture=fixture_name, slug=slug),
                }
                for rel, content in test_files.items():
                    sbx.write(rel, content)
                with_fix = sbx.pytest(test_rel)
                suite = sbx.pytest("tests")
                compile_errors = sbx.compile_check(changed + [test_rel])
                patch = sbx.diff()
            with Sandbox(repo, "HEAD", timeout, agent=self.name) as sbx:
                for rel, content in test_files.items():
                    sbx.write(rel, content)
                without_fix = sbx.pytest(test_rel)
                r_head = sbx.replay(service, traffic, rt_incident)
            return {"ok": True, "patch": patch, "code_patch": fixed_patch, "files": changed + list(test_files),
                    "description": desc, "test_files": test_files, "repro_test": test_rel,
                    "tests": {"repro_without_fix": without_fix, "repro_with_fix": with_fix, "suite": suite,
                              "compile_errors": compile_errors},
                    "replay": {"head": signature_rate(r_head, sigs), "fixed": signature_rate(r_fixed, sigs),
                               "pre": signature_rate(r_pre, sigs), "threshold": threshold, "signatures": sigs}}

        try:
            out = await asyncio.to_thread(work)
        except (SandboxError, ValueError) as exc:
            out = {"ok": False, "error": str(exc)}
        if not out.get("ok") and out.get("needs_llm_patch") and llm.live:
            out["error"] += " (LLM patch generation available but not attempted without a reviewer loop)"
        fix = {"kind": hyp["fix_kind"], **out}
        if out.get("ok"):
            t = out["tests"]
            secrets = scan_secrets("\n".join(l for l in out["patch"].splitlines() if l.startswith("+")))
            fix["checks"] = {
                "repro_fails_before": not t["repro_without_fix"]["ok"],
                "repro_passes_after": t["repro_with_fix"]["ok"],
                "suite_passes": t["suite"]["ok"],
                "static_clean": not t["compile_errors"],
                "no_secrets": not secrets,
            }
            fix["ok"] = all(fix["checks"].values())
            fix["summary"] = (f"{out['description']}; reproduction test fails before / passes after: "
                              f"{fix['checks']['repro_fails_before']}/{fix['checks']['repro_passes_after']}; "
                              f"suite {t['suite']['passed']} passed")
            fix["branch"] = f"aegis/fix-{task.incident.incident_id.lower()}"
            fix["approval_tool"] = "git.create_fix_branch"
            # the fixture is large; keep the stored copy of test files light
            fix["test_files_digest"] = {k: len(v) for k, v in out["test_files"].items()}
        else:
            fix["summary"] = f"could not prepare a patch: {out.get('error')}"
        return fix

    # -- operational remediations --------------------------------------------------------
    async def ops_fix(self, task: AgentTask, gw: ToolGateway, hyp: dict) -> dict:
        service, onset = task.incident.service, task.params["onset"]
        culprit = hyp["culprit"]
        pkg = service.replace("-", "_")
        if culprit.get("type") == "flag":
            actions = [{"tool": "ops.set_feature_flag", "args": {"flag": culprit["id"], "enabled": False,
                                                                 "reason": f"{task.incident.incident_id}: {hyp['title']}"}}]
            desc = f"disable feature flag {culprit['id']}"
        elif culprit.get("type") == "dependency":
            actions = [{"tool": "ops.set_feature_flag", "args": {"flag": f"{pkg}_gateway_fallback", "enabled": True,
                                                                 "reason": f"{culprit['id']} outage"}}]
            desc = f"enable {pkg}_gateway_fallback to serve degraded responses while {culprit['id']} is down"
        elif culprit.get("type") == "certificate":
            actions = [{"tool": "ops.rotate_certificate", "args": {"host": culprit["id"],
                                                                   "reason": "certificate expired"}}]
            desc = f"rotate the client certificate for {culprit['id']}"
        else:
            return {"kind": "manual", "ok": False, "summary": "no ops remediation known", "actions": []}
        repo = Path(task.workspace) / "repo"
        traffic, pre = await incident_traffic(gw, service, onset)
        rt_incident, rt_fixed = runtime_for(hyp, task.params["evidence"], service)

        def work():
            with Sandbox(repo, "HEAD", get_settings().sandbox_timeout_s, agent=self.name) as sbx:
                return (sbx.replay(service, traffic, rt_incident), sbx.replay(service, traffic, rt_fixed),
                        sbx.replay(service, pre, rt_fixed))

        r_head, r_fix, r_pre = await asyncio.to_thread(work)
        sigs = signatures(task.params["evidence"])
        reproduced, resolved, rates = replay_verdict(r_head, r_fix, r_pre, sigs)
        e_head, e_fix, e_pre = (rates["signature_rate_head"], rates["signature_rate_fixed"],
                                rates["signature_rate_pre"])
        detail = (f"replay ({'/'.join(sigs) or 'all errors'}): {e_head:.1%} now -> {e_fix:.1%} with remediation "
                  f"(pre-incident {e_pre:.1%})")
        return {"kind": "ops_action", "ok": resolved, "actions": actions, "description": desc,
                "summary": f"{desc}; {detail}", "approval_tool": actions[0]["tool"],
                "replay": {"head": e_head, "fixed": e_fix, "pre": e_pre, "reproduced": reproduced,
                           "resolved": resolved, "detail": detail}}

    async def pr_text(self, task: AgentTask, hyp: dict, fix: dict) -> dict:
        checks = fix.get("checks", {})
        body = (f"## Incident {task.incident.incident_id}\n\n**Root cause:** {hyp['title']} "
                f"(confidence {hyp['confidence']:.0%})\n\n{hyp.get('explanation', '')}\n\n"
                f"## Change\n{fix.get('description', fix.get('summary', ''))}\n\n## Verification\n"
                + "\n".join(f"- [{'x' if v else ' '}] {k.replace('_', ' ')}" for k, v in checks.items())
                + "\n\nPrepared by AegisAI in a sandbox. Requires human approval before merge.")
        default = PRText(title=f"fix({task.incident.service}): {hyp['title'][:60]}", body=body)
        llm = get_llm()
        pr, _ = await llm.structured(task="report", system="You write concise pull request descriptions.",
                                     prompt=f"Rewrite this PR description to be clear and concise. Keep the "
                                            f"checklist.\n\n{body}", schema=PRText, fallback=lambda: default)
        return pr.model_dump()

    # -- after approval ------------------------------------------------------------------
    async def apply(self, task: AgentTask, gw: ToolGateway) -> AgentResult:
        fix, token = task.params["fix"], task.params.get("approval_token")
        results = []
        if fix["kind"] == "ops_action":
            for i, action in enumerate(fix["actions"]):
                results.append(await gw.call(action["tool"], approval_token=token if i == 0 else None,
                                             **action["args"]))
        else:
            results.append(await gw.call("git.create_fix_branch", approval_token=token, branch=fix["branch"],
                                         patch=fix["patch"], message=fix["pr"]["title"]))
        return AgentResult(task_id=task.task_id, agent=self.name, summary=f"applied: {results}",
                           data={"applied": results})
